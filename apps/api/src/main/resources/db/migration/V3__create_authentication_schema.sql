-- RutaSur - Persistencia para sesiones y tokens de autenticación.
-- No se almacenan access tokens ni refresh tokens en texto plano.

create type estado_sesion as enum ('ACTIVA', 'INVALIDADA', 'EXPIRADA');
create type motivo_invalidacion_sesion as enum (
    'CIERRE_SESION', 'ROTACION_COMPROMETIDA', 'CAMBIO_CONTRASENA', 'BLOQUEO_USUARIO', 'ACCION_ADMINISTRATIVA'
);
create type tipo_evento_autenticacion as enum (
    'INICIO_SESION_EXITOSO', 'INICIO_SESION_FALLIDO', 'REFRESH_TOKEN_USADO',
    'REFRESH_TOKEN_REUTILIZADO', 'CIERRE_SESION', 'SESION_INVALIDADA'
);

create table sesion_autenticacion (
    id uuid primary key,
    usuario_id bigint not null references usuario(id),
    estado estado_sesion not null default 'ACTIVA',
    creada_en timestamptz not null default current_timestamp,
    ultimo_uso_en timestamptz not null default current_timestamp,
    expira_en timestamptz not null,
    invalidada_en timestamptz,
    motivo_invalidacion motivo_invalidacion_sesion,
    ip_creacion inet,
    agente_usuario varchar(500),
    check ((estado = 'INVALIDADA') = (invalidada_en is not null)),
    check (expira_en > creada_en)
);

create table refresh_token (
    id uuid primary key,
    sesion_id uuid not null references sesion_autenticacion(id),
    token_hash varchar(255) not null unique,
    creado_en timestamptz not null default current_timestamp,
    expira_en timestamptz not null,
    usado_en timestamptz,
    revocado_en timestamptz,
    reemplazado_por_id uuid unique references refresh_token(id),
    ip_creacion inet,
    agente_usuario varchar(500),
    check (expira_en > creado_en),
    check (reemplazado_por_id is null or usado_en is not null)
);

create table access_token_revocado (
    id bigint generated by default as identity primary key,
    jti uuid not null unique,
    usuario_id bigint not null references usuario(id),
    sesion_id uuid references sesion_autenticacion(id),
    revocado_en timestamptz not null default current_timestamp,
    expira_en timestamptz not null,
    motivo varchar(100) not null,
    check (expira_en > revocado_en)
);

create table evento_autenticacion (
    id bigint generated by default as identity primary key,
    usuario_id bigint references usuario(id),
    sesion_id uuid references sesion_autenticacion(id),
    tipo tipo_evento_autenticacion not null,
    ocurrido_en timestamptz not null default current_timestamp,
    ip inet,
    agente_usuario varchar(500),
    detalle varchar(500)
);

create index idx_sesion_autenticacion_usuario_estado on sesion_autenticacion (usuario_id, estado);
create index idx_refresh_token_sesion on refresh_token (sesion_id);
create index idx_refresh_token_expira_en on refresh_token (expira_en);
create index idx_access_token_revocado_expira_en on access_token_revocado (expira_en);
create index idx_evento_autenticacion_usuario_ocurrido on evento_autenticacion (usuario_id, ocurrido_en desc);

