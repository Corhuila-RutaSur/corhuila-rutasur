create type estado_reserva as enum ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'FINALIZADA');
create type estado_pago as enum ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'REEMBOLSADO');
create type estado_asistencia as enum ('PENDIENTE', 'ASISTIO', 'NO_ASISTIO', 'CANCELADO');
create type estado_salida as enum ('PROGRAMADA', 'ABIERTA', 'CERRADA', 'EN_EJECUCION', 'FINALIZADA', 'CANCELADA');
create type estado_ejecucion as enum ('PENDIENTE', 'EN_CURSO', 'FINALIZADA', 'CANCELADA');
create type tipo_servicio as enum ('TRANSPORTE', 'ALOJAMIENTO', 'ACTIVIDAD', 'ALIMENTACION');

create table tipo_usuario (
    id bigint generated by default as identity primary key,
    nombre varchar(50) not null unique,
    descripcion varchar(255),
    activo boolean not null default true
);

create table usuario (
    id bigint generated by default as identity primary key,
    tipo_documento varchar(20) not null,
    numero_documento varchar(30) not null unique,
    nombres varchar(100) not null,
    apellidos varchar(100) not null,
    correo varchar(150) not null unique,
    telefono varchar(30),
    password_hash varchar(255) not null,
    activo boolean not null default true,
    creado_en timestamptz not null default current_timestamp,
    actualizado_en timestamptz
);

create table usuario_tipo (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null references usuario(id),
    tipo_usuario_id bigint not null references tipo_usuario(id),
    asignado_en timestamptz not null default current_timestamp,
    unique (usuario_id, tipo_usuario_id)
);

create table guia (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null unique references usuario(id),
    numero_registro varchar(50),
    observaciones varchar(500),
    activo boolean not null default true
);

create table conductor (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null unique references usuario(id),
    numero_licencia varchar(50) not null unique,
    categoria_licencia varchar(20),
    vencimiento_licencia date,
    activo boolean not null default true
);

create table tipo_experiencia (
    id bigint generated by default as identity primary key,
    nombre varchar(80) not null unique,
    descripcion varchar(255),
    activo boolean not null default true
);

create table experiencia (
    id bigint generated by default as identity primary key,
    tipo_experiencia_id bigint not null references tipo_experiencia(id),
    nombre varchar(150) not null,
    descripcion text not null,
    destino varchar(150) not null,
    duracion_horas integer check (duracion_horas is null or duracion_horas > 0),
    recomendaciones text,
    activo boolean not null default true,
    creado_en timestamptz not null default current_timestamp,
    actualizado_en timestamptz
);

create table experiencia_imagen (
    id bigint generated by default as identity primary key,
    experiencia_id bigint not null references experiencia(id),
    url varchar(500) not null,
    descripcion varchar(255),
    orden integer not null default 1 check (orden > 0),
    principal boolean not null default false
);

create table servicio_experiencia (
    id bigint generated by default as identity primary key,
    experiencia_id bigint not null references experiencia(id),
    tipo tipo_servicio not null,
    nombre varchar(150) not null,
    descripcion text,
    activo boolean not null default true,
    unique (experiencia_id, nombre)
);

create table salida_experiencia (
    id bigint generated by default as identity primary key,
    experiencia_id bigint not null references experiencia(id),
    fecha_hora_inicio timestamptz not null,
    fecha_hora_fin timestamptz,
    cupos_totales integer not null check (cupos_totales > 0),
    cupos_disponibles integer not null check (cupos_disponibles between 0 and cupos_totales),
    estado estado_salida not null default 'PROGRAMADA',
    observaciones text,
    creado_en timestamptz not null default current_timestamp,
    check (fecha_hora_fin is null or fecha_hora_fin > fecha_hora_inicio)
);

create table programacion_servicio (
    id bigint generated by default as identity primary key,
    salida_experiencia_id bigint not null references salida_experiencia(id),
    servicio_experiencia_id bigint not null references servicio_experiencia(id),
    precio_unitario numeric(12, 2) not null check (precio_unitario >= 0),
    cupos_totales integer check (cupos_totales is null or cupos_totales > 0),
    cupos_disponibles integer,
    activo boolean not null default true,
    unique (salida_experiencia_id, servicio_experiencia_id),
    check (cupos_disponibles is null or (cupos_totales is not null and cupos_disponibles between 0 and cupos_totales))
);

create table reserva (
    id bigint generated by default as identity primary key,
    codigo varchar(30) not null unique,
    usuario_id bigint not null references usuario(id),
    salida_experiencia_id bigint not null references salida_experiencia(id),
    estado estado_reserva not null default 'PENDIENTE',
    subtotal numeric(12, 2) not null default 0 check (subtotal >= 0),
    descuento numeric(12, 2) not null default 0 check (descuento >= 0),
    total numeric(12, 2) not null default 0 check (total >= 0),
    fecha_reserva timestamptz not null default current_timestamp,
    observaciones text,
    check (total = subtotal - descuento)
);

create table participante_reserva (
    id bigint generated by default as identity primary key,
    reserva_id bigint not null references reserva(id),
    tipo_documento varchar(20),
    numero_documento varchar(30),
    nombres varchar(100) not null,
    apellidos varchar(100) not null,
    telefono varchar(30),
    correo varchar(150),
    es_responsable boolean not null default false
);

create unique index uk_participante_reserva_responsable
    on participante_reserva (reserva_id) where es_responsable;

create table detalle_reserva (
    id bigint generated by default as identity primary key,
    reserva_id bigint not null references reserva(id),
    programacion_servicio_id bigint not null references programacion_servicio(id),
    cantidad integer not null check (cantidad > 0),
    precio_unitario numeric(12, 2) not null check (precio_unitario >= 0),
    subtotal numeric(12, 2) not null check (subtotal >= 0),
    unique (reserva_id, programacion_servicio_id),
    check (subtotal = cantidad * precio_unitario)
);

create table detalle_participante (
    id bigint generated by default as identity primary key,
    detalle_reserva_id bigint not null references detalle_reserva(id),
    participante_reserva_id bigint not null references participante_reserva(id),
    asistencia estado_asistencia not null default 'PENDIENTE',
    unique (detalle_reserva_id, participante_reserva_id)
);

create table pago (
    id bigint generated by default as identity primary key,
    reserva_id bigint not null references reserva(id),
    referencia varchar(100) unique,
    metodo_pago varchar(50) not null,
    valor numeric(12, 2) not null check (valor > 0),
    estado estado_pago not null default 'PENDIENTE',
    fecha_pago timestamptz,
    respuesta_pasarela text,
    creado_en timestamptz not null default current_timestamp
);

create table calificacion (
    id bigint generated by default as identity primary key,
    reserva_id bigint not null unique references reserva(id),
    puntuacion smallint not null check (puntuacion between 1 and 5),
    comentario varchar(1000),
    fecha_calificacion timestamptz not null default current_timestamp
);

create table vehiculo (
    id bigint generated by default as identity primary key,
    placa varchar(10) not null unique,
    tipo varchar(50) not null,
    capacidad integer not null check (capacidad > 0),
    marca varchar(80),
    modelo varchar(80),
    activo boolean not null default true
);

create table ejecucion_experiencia (
    id bigint generated by default as identity primary key,
    salida_experiencia_id bigint not null unique references salida_experiencia(id),
    guia_id bigint not null references guia(id),
    fecha_hora_inicio_real timestamptz,
    fecha_hora_fin_real timestamptz,
    estado estado_ejecucion not null default 'PENDIENTE',
    observaciones text,
    check (fecha_hora_fin_real is null or fecha_hora_inicio_real is null or fecha_hora_fin_real > fecha_hora_inicio_real)
);

create table ejecucion_servicio (
    id bigint generated by default as identity primary key,
    programacion_servicio_id bigint not null unique references programacion_servicio(id),
    conductor_id bigint references conductor(id),
    vehiculo_id bigint references vehiculo(id),
    fecha_hora_inicio_real timestamptz,
    fecha_hora_fin_real timestamptz,
    estado estado_ejecucion not null default 'PENDIENTE',
    observaciones text,
    check (fecha_hora_fin_real is null or fecha_hora_inicio_real is null or fecha_hora_fin_real > fecha_hora_inicio_real)
);

-- Reglas transversales que no se pueden expresar solo con llaves foraneas.
create function validar_servicio_de_la_salida()
returns trigger language plpgsql as $$
begin
    if not exists (
        select 1
        from salida_experiencia se
        join servicio_experiencia sx on sx.experiencia_id = se.experiencia_id
        where se.id = new.salida_experiencia_id
          and sx.id = new.servicio_experiencia_id
    ) then
        raise exception 'El servicio programado debe pertenecer a la experiencia de la salida';
    end if;
    return new;
end;
$$;

create trigger trg_validar_servicio_de_la_salida
before insert or update of salida_experiencia_id, servicio_experiencia_id on programacion_servicio
for each row execute function validar_servicio_de_la_salida();

create function validar_detalle_de_la_reserva()
returns trigger language plpgsql as $$
begin
    if not exists (
        select 1
        from reserva r
        join programacion_servicio ps on ps.salida_experiencia_id = r.salida_experiencia_id
        where r.id = new.reserva_id
          and ps.id = new.programacion_servicio_id
    ) then
        raise exception 'El servicio seleccionado debe pertenecer a la misma salida de la reserva';
    end if;
    return new;
end;
$$;

create trigger trg_validar_detalle_de_la_reserva
before insert or update of reserva_id, programacion_servicio_id on detalle_reserva
for each row execute function validar_detalle_de_la_reserva();

create function validar_participante_de_la_reserva()
returns trigger language plpgsql as $$
begin
    if not exists (
        select 1
        from detalle_reserva dr
        join participante_reserva pr on pr.reserva_id = dr.reserva_id
        where dr.id = new.detalle_reserva_id
          and pr.id = new.participante_reserva_id
    ) then
        raise exception 'El participante debe pertenecer a la misma reserva del detalle';
    end if;
    return new;
end;
$$;

create trigger trg_validar_participante_de_la_reserva
before insert or update of detalle_reserva_id, participante_reserva_id on detalle_participante
for each row execute function validar_participante_de_la_reserva();

